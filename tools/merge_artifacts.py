#!/usr/bin/env python3
"""Merge the Breakthrough Companion + My 1:1 Breakthrough artifacts into one app.

Usage: python3 tools/merge_artifacts.py src/companion.html src/one-on-one.html public/app-bundle.html

Companion views keep their names. 1:1-only views are renamed so nothing collides:
  1:1 Dashboard.dc.html -> OneOnOne.dc.html (slug "one")
  1:1 Main.dc.html      -> RepTest.dc.html  (slug "rep")
  1:1 ECT.dc.html       -> ECT.dc.html      (slug "ect")
BreakingOut is shared, so the Companion copy is used.
The router is replaced by public/js/shell.js (login, sync, menu, video player).
"""
import os, re, sys

comp_path, one_path, out_path = sys.argv[1:4]
A = open(comp_path, encoding='utf-8').read()
B = open(one_path, encoding='utf-8').read()


def css_block(s):
    i = s.find('<style>\n', s.find('<title>'))
    j = s.find('</style>', i)
    return s[i + 8:j]


def css_sections(css):
    """Split into {name: text} on '/* name */' markers; '_pre' = text before the first."""
    parts = re.split(r'^/\* ([a-z]+) \*/$', css, flags=re.M)
    out = {'_pre': parts[0]}
    for k in range(1, len(parts), 2):
        out[parts[k]] = parts[k + 1]
    return out


def templates(s):
    return {m.group(1): m.group(0) for m in re.finditer(r'<template id="t-([a-z]+)">.*?</template>', s, re.S)}


def views(s):
    i = s.find('var VIEWS = {};')
    j = s.find('var current = null;', i)
    body = s[i + len('var VIEWS = {};'):j]
    chunks = re.split(r'(?=^VIEWS\[")', body, flags=re.M)
    out = {}
    for c in chunks:
        m = re.match(r'VIEWS\["([^"]+)"\]', c)
        if m:
            out[m.group(1)] = c
    return out


def runtime(s):
    i = s.find('<script>')
    j = s.find('var VIEWS = {};')
    return s[i + 8:j]


RENAMES = {'Dashboard.dc.html': 'OneOnOne.dc.html', 'Main.dc.html': 'RepTest.dc.html'}


def rename_routes(text):
    for old, new in RENAMES.items():
        text = text.replace('"' + old + '"', '"' + new + '"').replace("'" + old + "'", "'" + new + "'")
    return text


ca, cb = css_sections(css_block(A)), css_sections(css_block(B))
ta, tb = templates(A), templates(B)
va, vb = views(A), views(B)

# ---- CSS
css = ca['_pre'] + '#v-one{background:#4E0C08}\n#v-ect{background:#FAF7F5}\n'
for k, v in ca.items():
    if k != '_pre':
        css += '/* %s */\n%s' % (k, v)
css += '/* one (1:1 dashboard) */\n' + cb['dash'].replace('#v-dash', '#v-one')
css += '/* rep */\n' + cb['rep'] + '/* ect */\n' + cb['ect']

# ---- templates
tpl = ''.join(ta[k] + '\n' for k in ta)
tpl += rename_routes(tb['dash'].replace('<template id="t-dash">', '<template id="t-one">', 1)) + '\n'
tpl += rename_routes(tb['rep']) + '\n' + rename_routes(tb['ect']) + '\n'

# ---- view code
code = 'var VIEWS = {};\n'
for k, v in va.items():
    code += v
one = vb['Dashboard.dc.html'].replace('VIEWS["Dashboard.dc.html"] = { slug: "dash"', 'VIEWS["OneOnOne.dc.html"] = { slug: "one", private: true', 1)
rep = vb['Main.dc.html'].replace('VIEWS["Main.dc.html"] = { slug: "rep"', 'VIEWS["RepTest.dc.html"] = { slug: "rep", private: true', 1)
ect = vb['ECT.dc.html'].replace('VIEWS["ECT.dc.html"] = { slug: "ect"', 'VIEWS["ECT.dc.html"] = { slug: "ect", private: true', 1)
for v in (one, rep, ect):
    assert 'private: true' in v, 'rename failed'
    code += rename_routes(v)

fonts = sorted(set(re.findall(r'<link rel="stylesheet" href="https://fonts\.googleapis\.com[^"]+">', A[:3000] + B[:3000])))

out = '''<!-- GENERATED by tools/merge_artifacts.py. Edit views here or re-run the merge. -->
%s
<style>
%s
</style>
%s
<script>
%s
%s
window.BT_VIEWS = VIEWS;
window.BT_build = build;
</script>
''' % ('\n'.join(fonts), css, tpl, runtime(A), code)

# Old Claude links -> the same tools inside the app
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from import_canvas import LINKMAP
for old, new in LINKMAP.items():
    out = out.replace(old, new)
open(out_path, 'w', encoding='utf-8').write(out)
print('wrote', out_path, len(out), 'bytes; views:', re.findall(r'^VIEWS\["([^"]+)"\]', code, re.M))
