#!/usr/bin/env python3
"""Rebuild public/index.html: merge the two source artifacts, then drop the result into the page template.
Run from the project folder:  python3 tools/build.py
"""
import os, subprocess, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(root)
subprocess.check_call([sys.executable, 'tools/patch_box_proof.py'])
subprocess.check_call([sys.executable, 'tools/patch_box_game.py'])
subprocess.check_call([sys.executable, 'tools/merge_artifacts.py', 'src/companion.html', 'src/one-on-one.html', 'src/app-bundle.html'])
tpl = open('src/index.template.html', encoding='utf-8').read()
bundle = open('src/app-bundle.html', encoding='utf-8').read()
assert '<!--APP-BUNDLE-->' in tpl
open('public/index.html', 'w', encoding='utf-8').write(tpl.replace('<!--APP-BUNDLE-->', bundle))
print('built public/index.html')

# Default course outline + resources (src/course-outline.json from tools/make_course_outline.py,
# src/resources.json). Loaded in <head> so the views can use them as soon as they start.
import json
outline = json.load(open('src/course-outline.json', encoding='utf-8'))
resources = json.load(open('src/resources.json', encoding='utf-8'))
# The search database: what people type (or tap) -> the resources, lessons and tips that help.
# Keep src/search-db.json updated whenever a resource, lesson or tool is added.
searchdb = json.load(open('src/search-db.json', encoding='utf-8'))
open('public/js/course-data.js', 'w', encoding='utf-8').write(
    '/* GENERATED by tools/build.py from src/course-outline.json + src/resources.json. */\n'
    'window.BT_COURSE_DEFAULT = ' + json.dumps(outline, ensure_ascii=False) + ';\n'
    'window.BT_RESOURCES = ' + json.dumps(resources, ensure_ascii=False) + ';\n'
    'window.BT_SEARCH_DB = ' + json.dumps(searchdb, ensure_ascii=False) + ';\n')
print('built public/js/course-data.js')
